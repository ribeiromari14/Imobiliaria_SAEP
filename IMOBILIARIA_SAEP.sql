CREATE DATABASE IF NOT EXISTS IMOBILIARIA_SAEP_DB;
USE IMOBILIARIA_SAEP_DB;

CREATE TABLE IF NOT EXISTS USUARIO(
	USU_ID INT AUTO_INCREMENT PRIMARY KEY,
    USU_NOME VARCHAR(100) NOT NULL,
    USU_EMAIL VARCHAR(100) NOT NULL,
    USU_SENHA VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS PROPRIETARIO(
	PRO_ID INT AUTO_INCREMENT PRIMARY KEY,
    PRO_NOME VARCHAR(100) NOT NULL,
    PRO_DATA_NASCIMENTO DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS IMOVEL(
	IMO_ID INT AUTO_INCREMENT PRIMARY KEY,
    IMO_NOME VARCHAR(100) NOT NULL,
    IMO_RUA VARCHAR(100) NOT NULL,
    IMO_CIDADE VARCHAR(100) NOT NULL,
    IMO_VALOR VARCHAR(100) NOT NULL,
    FK_PRO_ID INT NOT NULL,
    FOREIGN KEY (FK_PRO_ID) REFERENCES PROPRIETARIO(PRO_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS AGENDAMENTO(
	AGE_ID INT AUTO_INCREMENT PRIMARY KEY,
    AGE_DATA_HORA DATETIME NOT NULL,
    AGE_MOTIVO VARCHAR(100) NOT NULL,
    AGE_STATUS VARCHAR(30) NOT NULL,
    FK_IMO_ID INT NOT NULL,
    FK_PRO_ID INT NOT NULL,
    FOREIGN KEY (FK_IMO_ID) REFERENCES IMOVEL(IMO_ID) ON DELETE CASCADE,
    FOREIGN KEY (FK_PRO_ID) REFERENCES PROPRIETARIO(PRO_ID) ON DELETE CASCADE
);

